"use server";

import { redirect } from "next/navigation";
import { revalidatePath } from "next/cache";
import { z } from "zod";
import { getTenant } from "@/lib/tenant";
import { createDraftQuote, MAX_ENQUIRY_CHARS, QuoteError } from "@/lib/quote/engine";
import { AiError } from "@/lib/ai/provider";
import { MIN_CHARGE_CODE, priceLines, type QuoteLine } from "@/lib/quote/build";

// History for quotes is written by database triggers (0012_audit_triggers),
// so none of these actions write to audit_log themselves.

export async function generateQuote(_prev: string | null, form: FormData): Promise<string | null> {
  const enquiry = String(form.get("enquiry") ?? "").trim();
  if (enquiry.length < 20) return "Paste the customer's enquiry first.";
  if (enquiry.length > MAX_ENQUIRY_CHARS) return `That's too long (max ${MAX_ENQUIRY_CHARS} characters).`;
  const customer = z.uuid().nullable().safeParse(form.get("customer_id") || null);
  if (!customer.success) return "Unknown customer.";

  const tenant = await getTenant();
  let id: string;
  try {
    id = await createDraftQuote(tenant, enquiry, customer.data);
  } catch (e) {
    if (e instanceof QuoteError || e instanceof AiError) return e.message;
    console.error("generateQuote failed", (e as Error)?.name); // no enquiry text or keys in logs
    return "Something went wrong drafting this quote.";
  }
  redirect(`/app/quotes/${id}`);
}

const editedLine = z.object({
  rate_code: z.string().max(20).nullable(),
  description: z.string().trim().min(1, "Every line needs a description.").max(300),
  qty: z.coerce.number().min(0).max(100000),
  unit: z.string().max(20),
  unit_rate: z.coerce.number().min(0).max(1_000_000),
  source: z.enum(["ai", "human", "system"]),
  note: z.string().max(600).nullable(),
});
const linesPayload = z.array(editedLine).max(60);

/** Saves a reviewer's edits. Totals and the minimum-charge line are recomputed here, never trusted from the browser. */
export async function saveLines(quoteId: string, payload: unknown): Promise<{ error?: string }> {
  const parsed = linesPayload.safeParse(payload);
  if (!parsed.success) return { error: parsed.error.issues[0]?.message ?? "Some lines are invalid." };
  const { supabase, company } = await getTenant();

  const { data: quote } = await supabase.from("quotes").select("id, status, outcome").eq("id", quoteId).single();
  if (!quote) return { error: "Quote not found." };
  if (quote.status === "approved") return { error: "Approved quotes can't be edited." };

  // Lines tied to a rate code must use a real, active rate from this company.
  const { data: rates } = await supabase.from("rates_current").select("code, unit, status").eq("company_id", company.id);
  const active = new Map((rates ?? []).filter((r) => r.status === "active").map((r) => [r.code, r]));
  const lines: QuoteLine[] = [];
  for (const l of parsed.data) {
    if (l.rate_code === MIN_CHARGE_CODE) continue; // regenerated by priceLines
    if (l.rate_code && !active.has(l.rate_code)) return { error: `${l.rate_code} isn't in use on your price list any more.` };
    lines.push({ ...l, unit: l.rate_code ? active.get(l.rate_code)!.unit : l.unit, line_total: 0 });
  }

  const priced = priceLines(lines, company);
  const { error: delErr } = await supabase.from("quote_lines").delete().eq("quote_id", quoteId);
  if (delErr) return { error: "Couldn't save changes." };
  if (priced.lines.length) {
    const { error } = await supabase
      .from("quote_lines")
      .insert(priced.lines.map((l, i) => ({ ...l, quote_id: quoteId, company_id: company.id, position: i })));
    if (error) return { error: "Couldn't save changes." };
  }
  // A reviewer pricing a site-visit job by hand turns it into a normal quote.
  const outcome = priced.lines.length ? "quote" : quote.outcome;
  await supabase
    .from("quotes")
    .update({ subtotal: priced.subtotal, vat: priced.vat, total: priced.total, outcome })
    .eq("id", quoteId);
  revalidatePath(`/app/quotes/${quoteId}`);
  return {};
}

const statusChange = z.enum(["approved", "rejected", "draft"]);

export async function setStatus(quoteId: string, next: string): Promise<{ error?: string }> {
  const status = statusChange.safeParse(next);
  if (!status.success) return { error: "Unknown action." };
  const tenant = await getTenant();
  if (status.data !== "draft" && !tenant.can("quote.approve")) {
    return { error: "Only an owner or manager can approve or reject quotes." };
  }

  const { data: quote } = await tenant.supabase.from("quotes").select("status").eq("id", quoteId).single();
  if (!quote) return { error: "Quote not found." };
  if (quote.status === "approved") return { error: "This quote is already approved." };

  // approved_by / approved_at are stamped by the database trigger from the session.
  const { error } = await tenant.supabase.from("quotes").update({ status: status.data }).eq("id", quoteId);
  if (error) return { error: error.code === "P0001" ? error.message : "Couldn't update the quote." };
  revalidatePath(`/app/quotes/${quoteId}`);
  revalidatePath("/app/quotes");
  return {};
}

export async function setCustomer(quoteId: string, customerId: string | null): Promise<{ error?: string }> {
  const id = z.uuid().nullable().safeParse(customerId);
  if (!id.success) return { error: "Unknown customer." };
  const { supabase } = await getTenant();
  // The composite foreign key also stops a customer from another company being attached.
  const { error } = await supabase.from("quotes").update({ customer_id: id.data }).eq("id", quoteId);
  if (error) return { error: "Couldn't change the customer." };
  revalidatePath(`/app/quotes/${quoteId}`);
  return {};
}
